/*************************************************************
// long SM_LinearGaussPtCount()                              
*************************************************************/

long                       // rtn: gauss pt iCount for given polynomial degree 
SM_LinearGaussPtCount      // eff: solve for n in degree=2*n-1 
 (long iNtgrlDegree)       // in : integration accuracy, degree of polynomial 
                           //      exactly integrated. 
// modifies:  
// effects :  
{
  return(iNtgrlDegree/2 + 1) ;

} // end SM_LinearGaussPtCount  

/*************************************************************
// long SM_LinearNtgrlDegree()                               
*************************************************************/

long                       // rtn: iNtgrlDegree for given sample iCount 
 SM_LinearNtgrlDegree      // eff: solve for degree=2*n-1 
 (long iGptCount)          // in : number of sample points 
// modifies:  
// effects :  
{
  return(2*iGptCount - 1) ;

} // end SM_LinearNtgrlDegree  

